import { readFile, realpath } from "node:fs/promises";
import { isAbsolute, join, relative, sep } from "node:path";

export type RoleName = "planner" | "architect" | "coder" | "qa" | "reviewer" | "security-auditor";
export const ROLE_NAMES: readonly RoleName[] = [
  "planner", "architect", "coder", "qa", "reviewer", "security-auditor",
];

export type ThinkingLevel = "off" | "minimal" | "low" | "medium" | "high" | "xhigh" | "max";
export const THINKING_LEVELS: readonly ThinkingLevel[] = [
  "off", "minimal", "low", "medium", "high", "xhigh", "max",
];

export interface RoleOverride {
  enabled?: boolean;
  model?: string;
  prompt?: string;
  promptAppend?: string;
  skills?: string[];
  tools?: string[];
  maxTurns?: number;
  thinking?: ThinkingLevel;
}

export interface TeamConfig {
  version: 1;
  board: string;
  dispatcherModel?: string;
  fixBudget: number;
  defaultFlow: "small" | "big";
  securityAudit: { trigger: "label" | "always" | "never"; label: string };
  roles: Record<string, RoleOverride>;
}

export interface AgentFrontmatter {
  description: string;
  tools: string[];
  model?: string;
  thinking?: ThinkingLevel;
  maxTurns?: number;
  skills: string[];
  isolation?: string;
}

export type RoleSource = "project-file" | "project-json" | "global-file" | "global-json" | "package-default";

export interface RoleDefinition extends AgentFrontmatter {
  name: RoleName;
  prompt: string;
  enabled: boolean;
  source: RoleSource;
  jsonIgnored: boolean;
}

export interface ResolvedConfig {
  board: string;
  dispatcherModel?: string;
  fixBudget: number;
  defaultFlow: "small" | "big";
  securityAudit: { trigger: "label" | "always" | "never"; label: string };
  roles: Record<RoleName, RoleDefinition>;
}

