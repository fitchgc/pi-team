export const GENERATED_MARKER = "<!-- Generated by pi-team from .pi/team.json. Hand-edit this file to take ownership; /team init will not overwrite it. -->";

export function isGeneratedAgentFile(text: string): boolean {
  return text.includes(GENERATED_MARKER);
}

function choice<Value extends string>(
  value: unknown,
  options: readonly Value[],
  field: string,
): Value {
  const match = options.find(option => option === value);
  if (match === undefined) throw new Error(`${field} must be one of ${options.join(", ")}`);
  return match;
}

function unquote(value: string): string {
  const first = value.charAt(0);
  return value.length >= 2 && (first === '"' || first === "'") && value.endsWith(first)
    ? value.slice(1, -1)
    : value;
}

export function parseAgentFile(text: string): { frontmatter: AgentFrontmatter; body: string } {
  const lines = text.split(/\r?\n/);
  const end = lines.indexOf("---", 1);
  if (lines[0] !== "---" || end < 0) {
    throw new Error("agent file: missing frontmatter delimiter");
  }

  const frontmatter: AgentFrontmatter = { description: "", tools: [], skills: [] };
  for (const line of lines.slice(1, end)) {
    if (!line.trim()) continue;
    const colon = line.indexOf(":");
    if (colon < 1) throw new Error(`agent file: invalid frontmatter line: ${line}`);
    const key = line.slice(0, colon).trim();
    const value = unquote(line.slice(colon + 1).trim());
    switch (key) {
      case "description":
      case "model":
      case "isolation":
        frontmatter[key] = value;
        break;
      case "tools":
      case "skills":
        frontmatter[key] = value.split(",").map(item => item.trim()).filter(Boolean);
        break;
      case "thinking":
        frontmatter.thinking = choice(value, THINKING_LEVELS, key);
        break;
      case "max_turns":
        if (!/^[+-]?\d+$/.test(value) || !Number.isSafeInteger(Number(value))) {
          throw new Error("agent file: max_turns must be an integer");
        }
        frontmatter.maxTurns = Number(value);
        break;
    }
  }

  const body = lines.slice(end + 1).join("\n").replace(/^(?:[^\S\n]*\n)+/, "").trimEnd();
  return { frontmatter, body };
}

export function renderAgentFile(def: RoleDefinition): string {
  const lines = ["---", `description: ${def.description}`, `tools: ${def.tools.join(", ")}`];
  if (def.model !== undefined) lines.push(`model: ${def.model}`);
  if (def.thinking !== undefined) lines.push(`thinking: ${def.thinking}`);
  if (def.maxTurns !== undefined) lines.push(`max_turns: ${def.maxTurns}`);
  if (def.skills.length) lines.push(`skills: ${def.skills.join(", ")}`);
  if (def.isolation !== undefined) lines.push(`isolation: ${def.isolation}`);
  return [...lines, "---", "", GENERATED_MARKER, "", def.prompt].join("\n");
}

type ConfigLayer = Partial<Omit<TeamConfig, "securityAudit" | "roles">> & {
  securityAudit?: Partial<TeamConfig["securityAudit"]>;
  roles?: TeamConfig["roles"];
};

function record(value: unknown, field: string): Record<string, unknown> {
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${field} must be an object`);
  }
  return value as Record<string, unknown>;
}

function stringValue(value: unknown, field: string, allowEmpty = false): string {
  if (typeof value !== "string" || (!allowEmpty && !value.trim())) {
    throw new Error(`${field} must be a ${allowEmpty ? "string" : "non-empty string"}`);
  }
  return value;
}

function integer(value: unknown, field: string, min: number, max: number): number {
  if (typeof value !== "number" || !Number.isInteger(value) || value < min || value > max) {
    throw new Error(`${field} must be an integer between ${min} and ${max}`);
  }
  return value;
}

function parseRole(value: unknown, name: string): RoleOverride {
  const role: RoleOverride = {};
  for (const [key, entry] of Object.entries(record(value, `roles.${name}`))) {
    const field = `roles.${name}.${key}`;
    switch (key) {
      case "enabled":
        if (typeof entry !== "boolean") throw new Error(`${field} must be a boolean`);
        role.enabled = entry;
        break;
      case "prompt":
      case "promptAppend":
      case "model":
        role[key] = stringValue(entry, field);
        break;
      case "skills":
      case "tools":
        if (!Array.isArray(entry)) throw new Error(`${field} must be an array`);
        role[key] = entry.map((item: unknown) => stringValue(item, field));
        break;
      case "thinking":
        role.thinking = choice(entry, THINKING_LEVELS, field);
        break;
      case "maxTurns":
        role.maxTurns = integer(entry, field, 1, Number.MAX_SAFE_INTEGER);
        break;
      default:
        throw new Error(`unknown role field: ${field}`);
    }
  }
  return role;
}

// Preserve absence until resolution: defaults in a project layer would mask global settings.
function parseLayer(text: string): ConfigLayer {
  const input = record(JSON.parse(text), "team.json");
  const layer: ConfigLayer = {};
  for (const [key, value] of Object.entries(input)) {
    switch (key) {
      case "version":
        if (value !== 1) throw new Error(`unsupported team.json version ${JSON.stringify(value)}`);
        layer.version = 1;
        break;
      case "$schema":
        stringValue(value, key, true);
        break;
      case "board":
      case "dispatcherModel":
        layer[key] = stringValue(value, key);
        break;
      case "fixBudget":
        layer.fixBudget = integer(value, key, 0, 10);
        break;
      case "defaultFlow":
        layer.defaultFlow = choice(value, ["small", "big"] as const, key);
        break;
      case "securityAudit": {
        const audit: Partial<TeamConfig["securityAudit"]> = {};
        for (const [field, entry] of Object.entries(record(value, key))) {
          if (field === "trigger") {
            audit.trigger = choice(entry, ["label", "always", "never"] as const, "securityAudit.trigger");
          } else if (field === "label") {
            audit.label = stringValue(entry, "securityAudit.label");
          } else {
            throw new Error(`unknown securityAudit field: ${field}`);
          }
        }
        layer.securityAudit = audit;
        break;
      }
      case "roles": {
        const roles: TeamConfig["roles"] = {};
        for (const [name, entry] of Object.entries(record(value, key))) {
          if (!ROLE_NAMES.some(role => role === name)) throw new Error(`unknown role: ${name}`);
          roles[name] = parseRole(entry, name);
        }
        layer.roles = roles;
        break;
      }
      default:
        throw new Error(`unknown team.json key: ${key}`);
    }
  }
  return layer;
}

function definedFields<Value extends object>(value: Value): Partial<Value> {
  return Object.fromEntries(Object.entries(value).filter(([, entry]) => entry !== undefined)) as Partial<Value>;
}

function mergeLayer(base: TeamConfig, over: ConfigLayer): TeamConfig {
  const { roles, securityAudit, ...scalars } = over;
  const mergedRoles = Object.fromEntries(
    [...new Set([...Object.keys(base.roles), ...Object.keys(roles ?? {})])].map(name => [
      name,
      structuredClone({ ...base.roles[name], ...definedFields(roles?.[name] ?? {}) }),
    ]),
  );
  return {
    ...base,
    ...definedFields(scalars),
    securityAudit: { ...base.securityAudit, ...definedFields(securityAudit ?? {}) },
    roles: mergedRoles,
  };
}

export function parseTeamConfig(text: string): TeamConfig {
  return mergeLayer(DEFAULT_CONFIG, parseLayer(text));
}

export function mergeTeamConfig(base: TeamConfig, over: TeamConfig): TeamConfig {
  return mergeLayer(base, over);
}

async function readOptional(root: string, ...parts: string[]): Promise<string | undefined> {
  try {
    const directory = await realpath(root);
    const file = await realpath(join(directory, ...parts));
    const suffix = relative(directory, file);
    if (isAbsolute(suffix) || suffix === ".." || suffix.startsWith(`..${sep}`)) {
      throw new Error(`config path escapes ${root}: ${parts.join("/")}`);
    }
    return await readFile(file, "utf8");
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") return undefined;
    throw error;
  }
}

async function readLayer(root: string, ...parts: string[]): Promise<ConfigLayer> {
  const text = await readOptional(root, ...parts);
  return text === undefined ? {} : parseLayer(text);
}

async function readAgent(root: string, ...parts: string[]): Promise<ReturnType<typeof parseAgentFile> | undefined> {
  const text = await readOptional(root, ...parts);
  return text === undefined ? undefined : parseAgentFile(text);
}

function applyRole(def: RoleDefinition, override: RoleOverride | undefined, source: RoleSource): RoleDefinition {
  if (!override || !Object.keys(override).length) return def;
  const { prompt, promptAppend, ...fields } = override;
  return {
    ...def,
    ...fields,
    source,
    prompt: prompt ?? (promptAppend === undefined ? def.prompt : `${def.prompt}\n\n${promptAppend}`),
  };
}

export async function resolveConfig(opts: {
  packageDir: string;
  projectDir: string;
  agentDir: string;
}): Promise<ResolvedConfig> {
  const [global, project] = await Promise.all([
    readLayer(opts.agentDir, "team.json"),
    readLayer(opts.projectDir, ".pi", "team.json"),
  ]);
  const config = mergeLayer(mergeLayer(DEFAULT_CONFIG, global), project);
  const roles = {} as Record<RoleName, RoleDefinition>;

  for (const name of ROLE_NAMES) {
    const file = `${name}.md`;
    const [packaged, globalFile, projectFile] = await Promise.all([
      readAgent(opts.packageDir, "agents", file),
      readAgent(opts.agentDir, "agents", file),
      readAgent(opts.projectDir, ".pi", "agents", file),
    ]);
    const globalRole = global.roles?.[name];
    const projectRole = project.roles?.[name];
    const base = projectFile ?? globalFile ?? packaged;
    const fallback = DEFAULT_CONFIG.roles[name] ?? {};
    let role: RoleDefinition = {
      ...(base?.frontmatter ?? {
        ...structuredClone(fallback),
        description: "",
        skills: [...(fallback.skills ?? [])],
        tools: [...(fallback.tools ?? [])],
      }),
      name,
      prompt: base?.body ?? "",
      source: projectFile ? "project-file" : globalFile ? "global-file" : "package-default",
      enabled: true,
      jsonIgnored: Boolean(projectFile || (globalFile && globalRole && Object.keys(globalRole).length)),
    };
    if (!projectFile) {
      if (!globalFile) role = applyRole(role, globalRole, "global-json");
      role = applyRole(role, projectRole, "project-json");
      if (role.source === "project-json") role.jsonIgnored = false;
    }
    // Activation belongs to Team config even when a file owns the Role definition.
    role.enabled = projectRole?.enabled ?? globalRole?.enabled ?? true;
    roles[name] = role;
  }

  const { board, dispatcherModel, fixBudget, defaultFlow, securityAudit } = config;
  return {
    board, fixBudget, defaultFlow, securityAudit, roles,
    ...(dispatcherModel === undefined ? {} : { dispatcherModel }),
  };
}
